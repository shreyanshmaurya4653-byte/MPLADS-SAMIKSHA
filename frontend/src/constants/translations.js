/**
 * Universal dynamic translator
 * @param {string} text - English string to translate
 * @param {string} lang - 'en' or 'hi'
 * @returns {string} Translated string if found, otherwise original
 */
export function translateDynamic(text, lang = 'en') {
  if (lang !== 'hi' || !text || typeof text !== 'string') {
    return text;
  }

  const trimmed = text.trim();

  // 1. Direct match in dictionary
  if (DYNAMIC_TERMS_HI[trimmed]) {
    return DYNAMIC_TERMS_HI[trimmed];
  }

  // 2. Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(DYNAMIC_TERMS_HI)) {
    if (key.toLowerCase() === lower) {
      return val;
    }
  }

  // 3. Dynamic patterns:
  // "MP: Shri Rajesh Kumar" -> "सांसद: Shri Rajesh Kumar"
  if (trimmed.startsWith('MP:')) {
    return `सांसद:${trimmed.slice(3)}`;
  }
  // "Work: 123" -> "कार्य: 123"
  if (trimmed.startsWith('Work:')) {
    return `कार्य:${trimmed.slice(5)}`;
  }
  // "Tier: MP" -> "स्तर: सांसद"
  if (trimmed.startsWith('Tier:')) {
    const rolePart = trimmed.slice(5).trim();
    return `स्तर: ${DYNAMIC_TERMS_HI[rolePart] || rolePart}`;
  }
  // "Constituency: ..." -> "संसदीय क्षेत्र: ..."
  if (trimmed.startsWith('Constituency:')) {
    return `संसदीय क्षेत्र:${trimmed.slice(13)}`;
  }
  // "District: ..." -> "ज़िला: ..."
  if (trimmed.startsWith('District:')) {
    return `ज़िला:${trimmed.slice(9)}`;
  }
  // "State: ..." -> "राज्य: ..."
  if (trimmed.startsWith('State:')) {
    return `राज्य:${trimmed.slice(6)}`;
  }

  return text;
}

