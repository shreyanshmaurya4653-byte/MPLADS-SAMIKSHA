/**
 * Deterministically resolve accurate geographical coordinates for a project work
 * @param {Object} work - The work record
 * @returns {[number, number]} [latitude, longitude]
 */
export function getWorkCoordinates(work) {
  if (!work) return [20.5937, 78.9629]; // India geographic center

  // 1. If explicit latitude & longitude exist
  if (work.latitude && work.longitude && !isNaN(work.latitude) && !isNaN(work.longitude)) {
    return [Number(work.latitude), Number(work.longitude)];
  }

  // 2. Lookup district
  const distName = (work.district_name || '').trim();
  let baseCoords = null;

  for (const [key, coords] of Object.entries(DISTRICT_COORDINATES)) {
    if (distName.toLowerCase() === key.toLowerCase() || distName.toLowerCase().includes(key.toLowerCase())) {
      baseCoords = coords;
      break;
    }
  }

  // 3. Fallback to state centroid
  if (!baseCoords) {
    const stateName = (work.state_name || '').trim();
    for (const [key, coords] of Object.entries(STATE_CENTROIDS)) {
      if (stateName.toLowerCase() === key.toLowerCase() || stateName.toLowerCase().includes(key.toLowerCase())) {
        baseCoords = coords;
        break;
      }
    }
  }

  // 4. Default to India center if not matched
  if (!baseCoords) {
    baseCoords = [20.5937, 78.9629];
  }

  // 5. Add micro-jitter (100m to 2.5km) so multiple works in the same district don't sit on the exact same pixel
  const idStr = String(work.id || work.title || '1');
  let hash = 0;
  for (let i = 0; i < idStr.length; i++) {
    hash = (hash << 5) - hash + idStr.charCodeAt(i);
    hash |= 0;
  }
  const angle = ((Math.abs(hash) % 360) * Math.PI) / 180;
  const radius = ((Math.abs(hash >> 3) % 100) / 100) * 0.045; // ~500m - 4.5km dispersion

  const lat = baseCoords[0] + radius * Math.cos(angle);
  const lng = baseCoords[1] + (radius * Math.sin(angle)) / Math.cos((baseCoords[0] * Math.PI) / 180);

  return [parseFloat(lat.toFixed(6)), parseFloat(lng.toFixed(6))];
}
